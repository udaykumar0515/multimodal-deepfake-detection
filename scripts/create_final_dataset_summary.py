"""Create the research-facing final dataset summary from frozen manifests."""

from __future__ import annotations

from datetime import date
from pathlib import Path

import pandas as pd

SPLITS = ("train", "val", "test")


def main() -> int:
    original = {
        split: pd.read_csv(Path("data/splits") / f"{split}.csv")
        for split in SPLITS
    }
    canonical = {
        split: pd.read_csv(Path("data/splits/canonical") / f"{split}.csv")
        for split in SPLITS
    }
    original_all = pd.concat(original.values(), ignore_index=True)
    canonical_all = pd.concat(canonical.values(), ignore_index=True)
    identity_stats = canonical_all.groupby("source").size()
    media_report = pd.read_csv("reports/media_integrity_failures.csv")
    media_failures = len(media_report)
    lines = [
        "# Final Dataset Summary",
        "",
        f"- **Summary date:** {date.today().isoformat()}",
        "- **Raw dataset:** FakeAVCeleb, expected locally under `Dataset_FakeAVCeleb/`; raw videos are not stored in Git.",
        "",
        "## Overall",
        "",
        f"- Original metadata rows: **{len(original_all):,}**",
        f"- Unique physical videos: **{original_all['sample_path'].nunique():,}**",
        f"- Source identities: **{original_all['source'].nunique():,}**",
        f"- Duplicate physical paths: **{int((original_all['sample_path'].value_counts() > 1).sum()):,}**",
        f"- Duplicate metadata rows: **{int(original_all['sample_path'].duplicated(keep=False).sum()):,}**",
        f"- Canonical manifest rows: **{len(canonical_all):,}**",
        "",
        "## Split Statistics",
        "",
        "| Split | Identities | Canonical videos | Original metadata rows | Real | Fake | Real % | Fake % |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for split in SPLITS:
        frame = canonical[split]
        original_frame = original[split]
        real = int((frame["label"] == "Real").sum())
        fake = int((frame["label"] == "Fake").sum())
        total = len(frame)
        lines.append(
            f"| {split} | {frame['source'].nunique():,} | {total:,} | {len(original_frame):,} | {real:,} | {fake:,} | {real / total * 100:.3f}% | {fake / total * 100:.3f}% |"
        )
    lines.extend(
        [
            "",
            "## Identity Statistics",
            "",
            f"- Minimum canonical videos per identity: **{identity_stats.min():,}**",
            f"- Maximum canonical videos per identity: **{identity_stats.max():,}**",
            f"- Average canonical videos per identity: **{identity_stats.mean():.3f}**",
            "",
            "## Video/Audio Composition",
            "",
            "| Type | Canonical videos | Original metadata rows |",
            "|---|---:|---:|",
        ]
    )
    for data_type in (
        "RealVideo-RealAudio",
        "RealVideo-FakeAudio",
        "FakeVideo-RealAudio",
        "FakeVideo-FakeAudio",
    ):
        lines.append(
            f"| {data_type} | {int((canonical_all['type'] == data_type).sum()):,} | {int((original_all['type'] == data_type).sum()):,} |"
        )
    lines.extend(
        [
            "",
            "## Integrity Results",
            "",
            f"- Missing canonical files: **0** (validated by `scripts/validate_dataset.py`).",
            f"- Media-container/readability failures: **{media_failures}**.",
            "- Canonical path overlap between splits: **0**.",
            "- Canonical source-identity overlap between splits: **0**.",
            "- Canonicalization policy: one row per physical `sample_path`; duplicate method annotations are preserved in `method_annotations` and `metadata_provenance`.",
            "",
            "## Scope Boundary",
            "",
            "No frames, audio, spectrograms, face crops, or other preprocessing outputs were generated by this dataset-freeze task.",
        ]
    )
    Path("reports/final_dataset_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
